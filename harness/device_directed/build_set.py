#!/usr/bin/env python3
"""Build brief 19's test set: device instructions spliced into streams of other speech, with known answers.

Sources (fetched by fetch_sources.sh; none of their text is committed, only this recipe and the ids it picks):
  instructions  SLURP (github.com/pswietojanski/slurp, text CC BY 4.0): real spoken commands. The train split teaches
                the shape models what each device's instructions look like; only test-split commands are spliced.
  streams       ami         AMI meeting transcripts (CC BY 4.0), per meeting, in time order, one sentence per phrase,
                            from the AMICorpusXML snapshot (zenodo.org/records/3561298)
                calls       Switchboard telephone calls (via SWDA, github.com/cgpotts/swda), one utterance per phrase,
                            each tagged with its caller: the speakerphone case
                lyrics      William Blake, Songs of Innocence and of Experience (1789-94), and the Psalms of the King
                            James Bible (1611): public-domain songs, from NLTK's Gutenberg selection; one line (Blake) or
                            verse (Psalms) per phrase
                monologue   long speeches from Shakespeare's Hamlet, Macbeth and Julius Caesar (public domain; NLTK),
                            one line per phrase. A stand-in: no free corpus of real self-talk (muttering, thinking aloud)
                            was reachable from this environment
  background    the Brown corpus (NLTK): general English, for the shape models' "fits English in general" side

Devices, by SLURP intent:
  car      transport_* (directions, traffic, taxi, tickets), email_sendemail, email_addcontact, social_post: navigation
           and messaging. SLURP has no phone-call intents.
  kitchen  cooking_*, iot_coffee, takeaway_*: SLURP has almost no oven or timer commands
  watch    alarm_*, calendar_* (reminders, events), datetime_query
  general  every other intent

A window is WINDOW consecutive phrases of one stream. One phrase is spliced in, whole, at a random position away from
the edges: a test-split instruction (a positive), or a hard negative. Hard negatives are generated by templates here,
and every one is flagged generated:
  to_person   the same instruction said to a person: "I'll text Sam that I missed my flight" style rewrites of the
              imperative test instructions (first-person plans, a named person asked, a reminder to someone)
  subject     talk about the device's subject, to a person ("did you set the oven to 400?"), slot-filled templates
A control, not generated: 'foreign', a real phrase of at least FOREIGN_MIN words from the other conversation stream (an
AMI sentence spliced into a call, a call utterance into a meeting). It is as out of place as a spliced instruction but not
meant for any device: a method that accepts it is finding the splice, not the device's shape. Its windows are built after
all the others, so adding it changed none of them.

usage: python3 build_set.py SOURCES_DIR OUT_DIR   (writes set.jsonl: one window per line, and instructions.json)
"""
import json
import random
import re
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

SEED = 19
WINDOW = 30
PER_CELL = 40            # positive windows per device and stream type
PER_CELL_SMALL = {'monologue': 10}   # a small source: fewer windows, so its lines are reused little
HARD_PER_KIND = 40       # hard-negative windows per device and kind
FOREIGN_MIN = 5
DEVICES = ('car', 'kitchen', 'watch', 'general')
STREAMS = ('ami', 'calls', 'lyrics', 'monologue')


def device_of(intent):
    s = intent.split('_', 1)[0]
    if s == 'transport' or intent in ('email_sendemail', 'email_addcontact', 'social_post'):
        return 'car'
    if s in ('cooking', 'takeaway') or intent == 'iot_coffee':
        return 'kitchen'
    if s in ('alarm', 'calendar') or intent == 'datetime_query':
        return 'watch'
    return 'general'


# ---------------------------------------------------------------- instructions
def instructions(src):
    out = {'train': defaultdict(list), 'test': defaultdict(list)}
    seen = set()
    for split, files in (('train', ['train', 'devel']), ('test', ['test'])):
        for f in files:
            for l in open(src / 'slurp' / f'{f}.jsonl'):
                d = json.loads(l)
                s = d['sentence'].strip()
                if len(s.split()) < 2:
                    continue
                key = s.lower()
                if split == 'test' and key in seen:
                    continue                    # a test command never also appears in training
                if split == 'train':
                    seen.add(key)
                out[split][device_of(d['intent'])].append({'slurp_id': d['slurp_id'], 'text': s, 'intent': d['intent']})
    return out


# ---------------------------------------------------------------- streams
def ami(src):
    z = zipfile.ZipFile(src / 'ami' / 'amixml.zip')
    docs = {}
    for n in sorted(z.namelist()):
        if '/data/ami-transcripts/' in n and n.endswith('.transcript.txt'):
            t = z.read(n).decode('utf-8', 'replace')
            sents = [s.strip() for s in re.split(r'(?<=[.?!])\s+', t) if s.strip()]
            docs[Path(n).name.split('.')[0]] = [{'text': s} for s in sents]
    return docs


SWDA_JUNK = re.compile(r'\{[A-Z] |[{}\[\]+/#]|<[^>]*>|\(\(|\)\)|--')


def calls(src):
    import csv
    import io
    z = zipfile.ZipFile(src / 'swda' / 'swda.zip')
    docs = defaultdict(list)
    for n in sorted(z.namelist()):
        if not n.endswith('.utt.csv') or '__MACOSX' in n:
            continue
        rows = list(csv.DictReader(io.TextIOWrapper(z.open(n), encoding='utf-8')))
        cur, key = [], None
        for r in rows:
            k = (r['caller'], r['utterance_index'])
            if k != key and cur:
                docs[n].append({'text': ' '.join(cur), 'caller': key[0]})
                cur = []
            key = k
            t = re.sub(r'\s+', ' ', SWDA_JUNK.sub(' ', r['text'])).strip(' ,')
            if t:
                cur.append(t)
        if cur:
            docs[n].append({'text': ' '.join(cur), 'caller': key[0]})
    return {Path(k).stem.replace('.utt', ''): [p for p in v if p['text'] and p['text'] not in ('.', ',')] for k, v in docs.items()}


def lyrics(src):
    z = zipfile.ZipFile(src / 'nltk' / 'gutenberg.zip')
    t = z.read('gutenberg/blake-poems.txt').decode('utf-8', 'replace')
    lines = [l.strip() for l in t.splitlines()]
    # skip titles (all capitals) and the bracketed header; keep verse lines
    verse = [l for l in lines if l and not l.isupper() and not l.startswith('[') and re.search('[a-z]', l)]
    kjv = z.read('gutenberg/bible-kjv.txt').decode('utf-8', 'replace')
    a, b = kjv.find('Book of Psalms'), kjv.find('The Proverbs')
    psalms = re.split(r'\s*\d+:\d+\s+', ' '.join(kjv[a:b].split()))[1:]
    return {'blake': [{'text': l} for l in verse], 'psalms': [{'text': v.strip()} for v in psalms if v.strip()]}


def monologue(src):
    z = zipfile.ZipFile(src / 'nltk' / 'gutenberg.zip')
    docs = {}
    for play in ('shakespeare-hamlet', 'shakespeare-macbeth', 'shakespeare-caesar'):
        t = z.read(f'gutenberg/{play}.txt').decode('utf-8', 'replace').splitlines()
        speeches, cur = [], None
        for l in t:
            m = re.match(r'^\s{2}([A-Z][a-z]+)\.\s+(.*)$', l)          # "  Ham. To be, or not to be..."
            if m:
                if cur:
                    speeches.append(cur)
                cur = [m.group(2)]
            elif cur is not None:
                if not l.strip() or l.strip().startswith(('Enter', 'Exit', 'Exeunt', 'Actus', 'Scena', 'Scoena')):
                    speeches.append(cur); cur = None
                else:
                    cur.append(l.strip())
        long = [s for s in speeches if len(s) >= 12]
        docs[play] = [{'text': l} for s in long for l in s if re.search('[A-Za-z]', l)]
    return docs


# ---------------------------------------------------------------- hard negatives
NAMES = ['Sam', 'Maria', 'Dave', 'Priya', 'Tom', 'Jen', 'Alex', 'Mum']
IMPERATIVE = re.compile(r'^(set|send|text|email|play|turn|remind|call|add|tell|start|book|order|find|show|give|wake|post|'
                        r'dim|make|put|cancel|delete|remove|schedule|get|check|read|open|stop|switch|create|look|search)\b')
TO_PERSON = [
    lambda c, n: f"I'll {c} when we get home",
    lambda c, n: f"I was going to {c} but I forgot",
    lambda c, n: f"{n}, can you {c} for me?",
    lambda c, n: f"remember to {c} tonight",
    lambda c, n: f"I need to {c} after this call",
]
SUBJECT = {
    'car': ["which exit do we take after the {place}?", "did you text {name} back about tonight?",
            "traffic on the {road} was terrible this morning", "I think we missed the turn for the {place}",
            "can you check the map, I don't know where the {place} is", "{name} sent me a message from the {place}",
            "should we get a taxi to the {place} or just walk?", "the train tickets were cheaper than I thought",
            "I'll drop you off at the {place} on the way", "the GPS kept telling me to turn left into a field"],
    'kitchen': ["did you set the oven to {temp}?", "how long has the chicken been in?", "the timer went off ten minutes ago",
                "we're out of coffee again", "what are we making for dinner tonight?", "{name} has the recipe for the {dish}",
                "I burned the {dish} last time", "should we just order takeaway?", "the coffee machine is making that noise again",
                "it says to bake it for forty minutes at {temp}"],
    'watch': ["what time is your alarm set for?", "I forgot about the meeting at {time}", "{name}'s birthday is next {day}",
              "did you put the dentist in the calendar?", "my alarm didn't go off this morning", "what's the date today, the {nth}?",
              "we have that thing with {name} on {day}", "I keep missing my reminders", "remind me what time the {event} starts",
              "I was up at {time} because of the alarm"],
    'general': ["did you see the weather for {day}?", "{name} played that song again all night", "what's the news saying about the {event}?",
                "turn it down, I can't hear you", "the lights in the {room} keep flickering", "I heard a joke about that on the radio",
                "what's the capital of Australia again?", "can you put it on the shopping list?", "who sings this one?",
                "I asked the speaker for the weather and it played music instead"],
}
FILL = {'place': ['station', 'airport', 'bridge', 'hospital', 'supermarket'], 'road': ['motorway', 'ring road', 'bridge'],
        'name': NAMES, 'temp': ['400', '180', '350', '200'], 'dish': ['lasagne', 'bread', 'curry', 'cake'],
        'time': ['three', 'ten', 'half past four', 'six'], 'day': ['Tuesday', 'Friday', 'weekend', 'Monday'],
        'nth': ['twelfth', 'fifth', 'twentieth'], 'event': ['election', 'match', 'concert', 'flood'],
        'room': ['kitchen', 'hall', 'bathroom']}


def to_person(rng, cmd):
    c = re.sub(r'\s*\bplease\b', '', cmd.lower()).strip(' .?!,')
    if not IMPERATIVE.match(c):
        return None
    f = rng.choice(TO_PERSON)
    s = f(c, rng.choice(NAMES))
    if s.startswith(("I'll", 'I was', 'I need')):
        s = re.sub(r'\bme\b', 'myself', s)
    return s[0].upper() + s[1:]


def subject(rng, device):
    t = rng.choice(SUBJECT[device])
    return re.sub(r'\{(\w+)\}', lambda m: rng.choice(FILL[m.group(1)]), t).capitalize()


# ---------------------------------------------------------------- windows
BLOCKS = {}


def window(rng, docs, kind):
    """A window of WINDOW phrases, from non-overlapping blocks of the stream drawn without replacement; a block is
    reused only once the stream runs out of fresh ones (only the small sources do)."""
    if not BLOCKS.get(kind):
        bl = [(k, a) for k, v in docs.items() for a in range(0, len(v) - WINDOW + 1, WINDOW)]
        rng.shuffle(bl)
        BLOCKS[kind] = bl
    k, a = BLOCKS[kind].pop()
    return k, a, [dict(p) for p in docs[k][a:a + WINDOW]]


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(SEED)
    ins = instructions(src)
    streams = {'ami': ami(src), 'calls': calls(src), 'lyrics': lyrics(src), 'monologue': monologue(src)}
    rows = []

    def splice(stream, phrase, meta):
        k, a, w = window(rng, streams[stream], stream)
        pos = rng.randrange(5, WINDOW - 5)
        p = {'text': phrase, **meta}
        if stream == 'calls':                                   # the speakerphone case: inside one caller's turn
            a_idx = [i for i in range(5, WINDOW - 5) if w[i - 1].get('caller') == 'A']
            pos = rng.choice(a_idx) if a_idx else pos
            p['caller'] = 'A'
        w.insert(pos, p)
        return {'stream': stream, 'source': k, 'start': a, 'pos': pos, 'phrases': w}

    test = {d: list(v) for d, v in ins['test'].items()}
    for d in DEVICES:
        rng.shuffle(test[d])
    used = Counter()
    for d in DEVICES:
        for s in STREAMS:
            for _ in range(PER_CELL_SMALL.get(s, PER_CELL)):
                i = test[d][used[d] % len(test[d])]
                used[d] += 1
                r = splice(s, i['text'], {'label': 'instruction', 'device': d, 'slurp_id': i['slurp_id'],
                                          'intent': i['intent'], 'generated': False})
                rows.append({'kind': 'instruction', 'device': d, **r})
        imps = [i for i in test[d] if IMPERATIVE.match(i['text'].lower())]
        for k in range(HARD_PER_KIND):
            s = ('ami', 'calls')[k % 2]
            base = imps[k % len(imps)] if imps else None
            ph = to_person(rng, base['text']) if base else None
            if ph:
                r = splice(s, ph, {'label': 'hard_negative', 'hard': 'to_person', 'device': d, 'slurp_id': base['slurp_id'],
                                   'generated': True})
                rows.append({'kind': 'hard_to_person', 'device': d, **r})
            r = splice(s, subject(rng, d), {'label': 'hard_negative', 'hard': 'subject', 'device': d, 'generated': True})
            rows.append({'kind': 'hard_subject', 'device': d, **r})
    # the foreign-phrase control, after everything else so the windows above are unchanged
    pool = {'ami': [p['text'] for v in streams['calls'].values() for p in v if len(p['text'].split()) >= FOREIGN_MIN],
            'calls': [p['text'] for v in streams['ami'].values() for p in v if len(p['text'].split()) >= FOREIGN_MIN]}
    for d in DEVICES:
        for k in range(HARD_PER_KIND):
            s = ('ami', 'calls')[k % 2]
            r = splice(s, rng.choice(pool[s]), {'label': 'hard_negative', 'hard': 'foreign', 'device': d, 'generated': False})
            rows.append({'kind': 'hard_foreign', 'device': d, **r})
    for n, r in enumerate(rows):
        r['id'] = f"w{n:04d}"
        for p in r['phrases']:
            p.setdefault('label', 'stream')
    with open(out / 'set.jsonl', 'w') as fh:
        for r in rows:
            fh.write(json.dumps(r) + '\n')
    train = {d: [i['text'] for i in v] for d, v in ins['train'].items()}
    (out / 'instructions_train.json').write_text(json.dumps(train))
    print(json.dumps({'windows': len(rows), 'by_kind': Counter(r['kind'] for r in rows),
                      'train_per_device': {d: len(v) for d, v in train.items()},
                      'test_per_device': {d: len(v) for d, v in ins['test'].items()},
                      'stream_docs': {k: len(v) for k, v in streams.items()},
                      'stream_phrases': {k: sum(len(x) for x in v.values()) for k, v in streams.items()}}, default=dict))


if __name__ == '__main__':
    main()
